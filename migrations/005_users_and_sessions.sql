-- 005: пользователи и сессии входа
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,      -- всегда в нижнем регистре
    name VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,             -- хеш argon2, сам пароль нигде не хранится
    role VARCHAR(20) NOT NULL DEFAULT 'manager',  -- admin / manager / printer
    position VARCHAR(255) NOT NULL DEFAULT 'Сотрудник',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash CHAR(64) PRIMARY KEY,         -- sha256 от токена, который лежит в cookie
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
