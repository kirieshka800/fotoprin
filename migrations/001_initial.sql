BEGIN;

CREATE TABLE meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    raw_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(id) ON DELETE CASCADE,
    summary_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    assignee VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed')),
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT
        REFERENCES tasks(id) ON DELETE SET NULL,
    text TEXT NOT NULL,
    remind_at TIMESTAMP NOT NULL,
    is_sent BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_summaries_meeting_id
    ON summaries(meeting_id);

CREATE INDEX idx_tasks_meeting_id
    ON tasks(meeting_id);

CREATE INDEX idx_tasks_assignee_status
    ON tasks(assignee, status);

CREATE INDEX idx_reminders_task_id
    ON reminders(task_id);

CREATE INDEX idx_reminders_unsent_due
    ON reminders(remind_at)
    WHERE is_sent = FALSE;

COMMIT;
