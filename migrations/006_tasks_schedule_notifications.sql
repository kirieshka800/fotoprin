-- ---------------------------------------------------------------------------
-- График работы
-- ---------------------------------------------------------------------------
-- status: confirmed — действующая смена, ai — предложение ассистента (ждёт решения).
-- Для ai-смены prev_* хранит прежнее время («было»). Минуты от начала суток;
-- end_min <= start_min — смена переходит на следующие сутки.
CREATE TABLE shifts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    shift_date      DATE NOT NULL,
    start_min       INTEGER NOT NULL CHECK (start_min BETWEEN 0 AND 1439),
    end_min         INTEGER NOT NULL CHECK (end_min BETWEEN 0 AND 1440),
    note            VARCHAR(255) NOT NULL DEFAULT '',
    status          VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'ai')),
    prev_start_min  INTEGER,
    prev_end_min    INTEGER,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_shift_employee_day UNIQUE (employee_id, shift_date)
);
CREATE INDEX idx_shifts_date   ON shifts(shift_date);
CREATE INDEX idx_shifts_status ON shifts(status) WHERE status = 'ai';

CREATE TABLE schedule_weeks (
    week_start      DATE PRIMARY KEY,
    published       BOOLEAN NOT NULL DEFAULT FALSE,
    published_at    TIMESTAMPTZ,
    proposal_text   TEXT,
    why_text        TEXT,
    why_source      VARCHAR(500),
    why_meeting_id  BIGINT REFERENCES meetings(id) ON DELETE SET NULL,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- Уведомления (по одной строке на получателя-сотрудника)
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    title         VARCHAR(500) NOT NULL,
    text          TEXT NOT NULL,
    category      VARCHAR(50) NOT NULL,
    action_label  VARCHAR(100) NOT NULL DEFAULT 'Открыть',
    href          VARCHAR(500) NOT NULL DEFAULT '',
    is_read       BOOLEAN NOT NULL DEFAULT FALSE,
    from_ai       BOOLEAN NOT NULL DEFAULT FALSE,
    kind          VARCHAR(50),
    ref_key       VARCHAR(100),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_notifications_recipient ON notifications(recipient_id, created_at DESC);
CREATE INDEX idx_notifications_unread    ON notifications(recipient_id) WHERE is_read = FALSE;
CREATE INDEX idx_notifications_kind      ON notifications(kind, ref_key) WHERE kind IS NOT NULL;
