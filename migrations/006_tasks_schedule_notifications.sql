UPDATE tasks SET status = 'done'    WHERE status = 'completed';
UPDATE tasks SET title  = LEFT(description, 200) WHERE title = '';
UPDATE tasks t SET source = m.title FROM meetings m WHERE t.meeting_id = m.id AND t.source IS NULL;
UPDATE tasks SET due_at = created_at + INTERVAL '1 day' WHERE due_at IS NULL;
UPDATE tasks SET completed_at = created_at WHERE status = 'done' AND completed_at IS NULL;
UPDATE tasks t SET assignee_id = e.id
    FROM employees e
    WHERE t.assignee_id IS NULL AND t.assignee IS NOT NULL AND LOWER(e.name) = LOWER(t.assignee);

