-- 003: данные для вкладки «Обзор» и создания встреч.
-- Старые миграции (001, 002) не меняем, только дополняем схему.

-- Отделы (для выбора при создании встречи). Список можно править обычным SQL.
CREATE TABLE IF NOT EXISTS departments (
    name VARCHAR(100) PRIMARY KEY
);

INSERT INTO departments (name) VALUES
    ('Производство'), ('Логистика'), ('Продукт'), ('Продажи'), ('Маркетинг')
ON CONFLICT (name) DO NOTHING;

-- Сотрудники (участники встреч). Изначально пусто: добавьте через POST /api/employees или SQL.
CREATE TABLE IF NOT EXISTS employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    position VARCHAR(255) NOT NULL DEFAULT '',
    department VARCHAR(100) NOT NULL DEFAULT '',
    role VARCHAR(50) NOT NULL DEFAULT 'Сотрудник'
);

-- Новые поля встречи
ALTER TABLE meetings
    ADD COLUMN IF NOT EXISTS department VARCHAR(100) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS meeting_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ADD COLUMN IF NOT EXISTS duration_min INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'ready',
    ADD COLUMN IF NOT EXISTS progress INTEGER NOT NULL DEFAULT 100,
    ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS error_message TEXT,
    ADD COLUMN IF NOT EXISTS source_name VARCHAR(500),
    ADD COLUMN IF NOT EXISTS actions JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS idx_meetings_date ON meetings(meeting_date DESC);
CREATE INDEX IF NOT EXISTS idx_meetings_status ON meetings(status);

-- Участники встречи
CREATE TABLE IF NOT EXISTS meeting_participants (
    meeting_id BIGINT NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    PRIMARY KEY (meeting_id, employee_id)
);

-- Новые поля задачи (название, срок текстом, основание из стенограммы)
ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS title TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS due_text VARCHAR(255) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS basis TEXT NOT NULL DEFAULT '';

-- Лента «Пока вы были заняты»
CREATE TABLE IF NOT EXISTS activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    title TEXT NOT NULL,
    text TEXT NOT NULL DEFAULT '',
    meeting_id BIGINT REFERENCES meetings(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_activity_created_at ON activity(created_at DESC);

-- Настройки рабочего пространства (одна строка, JSON)
CREATE TABLE IF NOT EXISTS app_settings (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    data JSONB NOT NULL
);
