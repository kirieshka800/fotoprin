-- Дополнительные таблицы для поддержки RAG (AI-01, AI-02) и Аудита (AI-06)

-- 1. Таблица корпоративных документов с ролевой моделью доступа
CREATE TABLE IF NOT EXISTS company_documents (
                                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                 title VARCHAR(500) NOT NULL,
    content TEXT NOT NULL,
    allowed_roles TEXT[] NOT NULL DEFAULT '{}', -- Массив ролей, имеющих доступ к документу (AI-02)
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
    );

-- Индекс для быстрого поиска по документам
CREATE INDEX IF NOT EXISTS idx_company_documents_title_content
    ON company_documents(title);

-- 2. Таблица для аудита запросов и действий ИИ (AI-06)
CREATE TABLE IF NOT EXISTS audit_logs (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          action VARCHAR(100) NOT NULL,          -- Название действия (например, PREVIEW_MEETING, CONFIRM_MEETING)
    user_role VARCHAR(100) NOT NULL,       -- Роль пользователя
    details TEXT,                          -- Запрос / контекст (с маскированием чувствительных данных)
    status VARCHAR(50) NOT NULL,           -- Статус выполнения (SUCCESS, ERROR, SAVED)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );

-- Индекс для аудита по дате и действиям
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
    ON audit_logs(created_at DESC);